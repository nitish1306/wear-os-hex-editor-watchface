# Generates res/raw/watchface.xml for the Hex Editor Watch Face Format face.
# The geometry mirrors the original CanvasWatchFaceService renderer:
#   tile size 78x46, columns x=-2..3, rows y=-5..5
#   x = 225 + (col - 1) * 78,  y = 225 + row * 56 - 24
$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$out = Join-Path $root 'src\main\res\raw\watchface.xml'

$sb = [System.Text.StringBuilder]::new()
function Add([string]$s) { [void]$sb.AppendLine($s) }

function Get-X([int]$col) { return 225 + ($col - 1) * 78 }
function Get-Y([int]$row) { return 225 + $row * 56 - 24 }

function Add-Tile([int]$col, [int]$row, [string]$res, [string]$indent) {
    $x = Get-X $col
    $y = Get-Y $row
    Add "$indent<PartImage x=`"$x`" y=`"$y`" width=`"78`" height=`"46`"><Image resource=`"$res`"/></PartImage>"
}

function Add-ValueCondition([int]$col, [int]$row, [string]$source, [int]$min, [int]$max, [string]$color) {
    Add '    <Condition>'
    Add '      <Expressions>'
    for ($v = $min; $v -le $max; $v++) {
        Add "        <Expression name=`"e$v`">[$source] == $v</Expression>"
    }
    Add '      </Expressions>'
    for ($v = $min; $v -le $max; $v++) {
        Add "      <Compare expression=`"e$v`">"
        Add-Tile $col $row ("d{0:D2}_$color" -f $v) '        '
        Add '      </Compare>'
    }
    Add '      <Default>'
    Add-Tile $col $row ("d{0:D2}_$color" -f $min) '        '
    Add '      </Default>'
    Add '    </Condition>'
}

Add '<?xml version="1.0" encoding="utf-8"?>'
Add '<!-- Generated by tools/generate_watchface.ps1. Do not edit by hand. -->'
Add '<WatchFace width="450" height="450">'
Add '  <Metadata key="CLOCK_TYPE" value="DIGITAL"/>'
Add '  <Metadata key="PREVIEW_TIME" value="10:08:32"/>'
Add '  <Scene backgroundColor="#ff000000">'

# Background texture (600x600, centered on the 450x450 scene like the original).
Add '    <PartImage x="-75" y="-75" width="600" height="600"><Image resource="bg_empty"/></PartImage>'

# Static field of cyan 0x00 tiles, dimmed in ambient mode.
Add '    <Group x="0" y="0" width="450" height="450" name="grid">'
Add '      <Variant mode="AMBIENT" target="alpha" value="40"/>'
for ($col = -2; $col -le 3; $col++) {
    for ($row = -5; $row -le 5; $row++) {
        Add-Tile $col $row 'd00_cyan' '      '
    }
}
Add '    </Group>'

# Live values, mirroring the original layout positions.
Add-ValueCondition 0 0 'HOUR_0_23' 0 23 'white'
Add-ValueCondition 1 0 'MINUTE'    0 59 'white'
Add-ValueCondition 2 0 'SECOND'    0 59 'cyan'
Add-ValueCondition 2 (-1) 'MONTH'    1 12 'cyan'
Add-ValueCondition 1 (-1) 'YEAR_S'   0 99 'cyan'
Add-ValueCondition 2 1 'DAY'       1 31 'cyan'
Add-ValueCondition 1 1 'DAY_OF_WEEK' 1 7 'cyan'

# Vignetting overlay.
Add '    <PartImage x="-25" y="-25" width="500" height="500"><Image resource="vignetting"/></PartImage>'

Add '  </Scene>'
Add '</WatchFace>'

[System.IO.File]::WriteAllText($out, $sb.ToString(), [System.Text.UTF8Encoding]::new($false))
Write-Output "Wrote $out ($([System.IO.File]::ReadAllLines($out).Count) lines)"
